"""Verify cached demographic dictionary, layer aliases and all published grouped shares."""
import collections,csv,decimal,hashlib,json,re
from pathlib import Path
from pypdf import PdfReader
ROOT=Path(__file__).resolve().parents[1]
GROUPS={'age':['pop_und10','pop_10_64','pop_ov64'],'race-ethnicity':['hisp','white','black','amind','asian','pacisl','othmult']}

def prepare():
    manifest=json.loads((ROOT/'data/raw/manifest.json').read_text())
    for name in ['ces.pdf','ces.csv','ces-layer.json']:
        assert hashlib.sha256((ROOT/'data/raw'/name).read_bytes()).hexdigest()==manifest[name]['sha256']
    reader=PdfReader(ROOT/'data/raw/ces.pdf')
    pages={n:re.sub(r'\s+',' ',reader.pages[n-1].extract_text()) for n in [4,5,6]}
    for phrase in ['Total Population 2024 5-year ACS population estimates','under 10 years old','between 10 and 64 years old','65 years and older']:assert phrase in pages[4]
    for phrase in ['identify as Hispanic or Latino','non-Hispanic white','non-Hispanic African American or black','non-Hispanic Native American','non-Hispanic Asian','non-Hispanic Pacific Islander','non-Hispanic "other" or as multiple races']:assert phrase in pages[5]
    assert '25 out of 9,106 census tracts reported zero population in the 2020–2024 ACS' in pages[6]
    layer=json.loads((ROOT/'data/raw/ces-layer.json').read_text())
    aliases={f['alias']:f['name'] for f in layer['fields'] if f['alias'] in ['ACS2024Pop']+sum(GROUPS.values(),[])}
    assert len(aliases)==11
    rows=json.loads((ROOT/'data/observations.json').read_text())
    originals={str(int(r['tract'])).zfill(11):r for r in csv.DictReader((ROOT/'data/raw/ces.csv').open(encoding='utf-8-sig'))}
    assert set(rows)==set(originals)
    for tid,row in rows.items():
        for field in ['ACS2024Pop']+sum(GROUPS.values(),[]):
            original=originals[tid][field]
            assert row[field] == (None if original in ['', 'NA'] else original), (tid,field)
    audit={}
    for group,fields in GROUPS.items():
        sums=[];missing=collections.Counter();zeros=0;max_places=0
        for tid,row in rows.items():
            values=[decimal.Decimal(row[f]) if row[f] is not None else None for f in fields]
            missing[sum(v is None for v in values)]+=1
            zeros+=sum(v==0 for v in values if v is not None)
            for v in values:
                if v is not None:
                    assert 0<=v<=100
                    max_places=max(max_places,max(0,-v.as_tuple().exponent))
            if all(v is not None for v in values):sums.append(sum(values))
            elif all(v is None for v in values):assert decimal.Decimal(row['ACS2024Pop'])==0
        assert max_places<=2
        audit[group]=dict(fields=fields,tractCount=len(rows),missingCategoryCountDistribution=dict(missing),zeroShareCount=zeros,sourceDecimalPlaces=max_places,minCompleteSumPercent=str(min(sums)),maxCompleteSumPercent=str(max(sums)),completeSumsNotExactly100=sum(v!=100 for v in sums),maxRoundingAllowancePercentagePoints=str(len(fields)*decimal.Decimal('0.005')))
    result=dict(contractVersion='atlas-demographic-evidence-v1',sourcePeriod='2020–2024 ACS 5-year',dictionaryPages=[4,5,6],
                originalCsvJoinCount=len(originals),canonicalSharesMatchedOriginalCsv=True,denominator=dict(concept='Tract population estimate as supplied by CES demographic profile',sourceField='ACS2024Pop',sourceLabel='Total Population',unit='people',categoryCountDerivation='none'),
                sourceAliases=aliases,audit=audit,sourceProvenance={name:manifest[name] for name in ['ces.pdf','ces.csv','ces-layer.json']},
                limitations=['Publisher-defined profile fields, not independently reconstructed ACS counts or reclassified race/ethnicity categories.','Rounding allowance describes arithmetic of reported two-decimal shares, not a confidence interval or margin of error.','Never normalize available shares to 100%, split combined Other/Multiple, or invent residual categories.'])
    (ROOT/'data/contracts/demographic-evidence.json').write_text(json.dumps(result,indent=2))
    (ROOT/'src/contracts/demographic-proof.ts').write_text('// Generated by scripts/verify_demographics.py.\nexport const DEMOGRAPHIC_PROOF = '+json.dumps(result,indent=2)+' as const;\n')
    print(json.dumps(audit,indent=2))
if __name__=='__main__':prepare()
